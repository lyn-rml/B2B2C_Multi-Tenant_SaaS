CREATE TABLE __tenant__.activities (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address_id BIGINT NOT NULL REFERENCES __tenant__.addresses(id) ON DELETE CASCADE,
    text       TEXT NOT NULL,
    image_path VARCHAR NOT NULL,
    process_id BIGINT REFERENCES public.process(id),
    shared     BOOLEAN NOT NULL DEFAULT false,
    active     BOOLEAN NOT NULL DEFAULT true,
    status     VARCHAR NOT NULL DEFAULT 'NOT_SHARED',
    CONSTRAINT activities_status_check CHECK (status IN ('SHARED', 'NOT_SHARED'))
);
