CREATE TABLE __tenant__.addresses (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label          VARCHAR NOT NULL,
    street_address VARCHAR NOT NULL,
    postal_code    VARCHAR NOT NULL,
    city           VARCHAR NOT NULL,
    country        VARCHAR NOT NULL DEFAULT 'France',
    active         BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE __tenant__.address_admins (
    address_id BIGINT NOT NULL REFERENCES __tenant__.addresses(id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    PRIMARY KEY (address_id, user_id)
);

CREATE TABLE __tenant__.employee_addresses (
    address_id BIGINT NOT NULL REFERENCES __tenant__.addresses(id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    PRIMARY KEY (address_id, user_id)
);
