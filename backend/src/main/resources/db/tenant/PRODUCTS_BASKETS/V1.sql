CREATE TABLE __tenant__.products (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address_id BIGINT NOT NULL REFERENCES __tenant__.addresses(id),
    name       VARCHAR NOT NULL,
    active     BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE __tenant__.product_batches (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT NOT NULL REFERENCES __tenant__.products(id),
    expiry_date DATE NOT NULL,
    quantity    NUMERIC NOT NULL,
    active      BOOLEAN NOT NULL DEFAULT true,
    CONSTRAINT product_batches_quantity_check CHECK (quantity >= 0)
);

CREATE INDEX product_batches_product_expiry_idx
    ON __tenant__.product_batches(product_id, expiry_date);

CREATE TABLE __tenant__.baskets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address_id  BIGINT NOT NULL REFERENCES __tenant__.addresses(id),
    process_id  BIGINT REFERENCES public.process(id),
    title       VARCHAR NOT NULL,
    description TEXT,
    price       NUMERIC,
    status      VARCHAR NOT NULL DEFAULT 'NOT_SHARED',
    shared      BOOLEAN NOT NULL DEFAULT false,
    active      BOOLEAN NOT NULL DEFAULT true,
    CONSTRAINT baskets_price_check CHECK (price >= 0),
    CONSTRAINT baskets_status_check CHECK (status IN ('SHARED', 'NOT_SHARED'))
);

CREATE INDEX baskets_shared_active_idx ON __tenant__.baskets(shared, active);

CREATE TABLE __tenant__.basket_items (
    basket_id        BIGINT NOT NULL REFERENCES __tenant__.baskets(id) ON DELETE CASCADE,
    product_batch_id BIGINT NOT NULL REFERENCES __tenant__.product_batches(id),
    quantity         NUMERIC NOT NULL,
    PRIMARY KEY (basket_id, product_batch_id),
    CONSTRAINT basket_items_quantity_check CHECK (quantity > 0)
);
