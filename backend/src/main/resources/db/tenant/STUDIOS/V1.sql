CREATE TABLE __tenant__.studios (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address_id   BIGINT NOT NULL REFERENCES __tenant__.addresses(id) ON DELETE CASCADE,
    process_id   BIGINT REFERENCES public.process(id),
    label        VARCHAR NOT NULL,
    surface_m2   NUMERIC,
    monthly_rent NUMERIC,
    status       VARCHAR NOT NULL DEFAULT 'NOT_SHARED',
    shared       BOOLEAN NOT NULL DEFAULT false,
    active       BOOLEAN NOT NULL DEFAULT true,
    CONSTRAINT studios_status_check CHECK (status IN ('SHARED', 'NOT_SHARED'))
);
