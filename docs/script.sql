-- PARTIE 1 : crée uniquement les 9 tables publiques, toutes vides.
-- PARTIES 2 à 5 : modèles SQL commentés, donc non exécutés.
-- Pour un tenant, remplacer __tenant__ par le nom de son schéma existant,
-- exécuter le socle commun (partie 2), puis les blocs des modules retenus.
-- L'insertion dans tenant_modules ne crée aucune table automatiquement.
--
-- Répartition :
--   Commun au tenant : addresses, address_admins, employee_addresses
--   PRODUCTS_BASKETS : products, product_batches, baskets, basket_items
--   STUDIOS          : studios
--   ACTIVITIES       : activities
-- Le catalogue public.modules est renseigné via l’API Platform Admin.
