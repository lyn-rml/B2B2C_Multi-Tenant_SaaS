-- ============================================================================
-- 1. TABLES PUBLIQUES — Exécutées
-- ============================================================================

BEGIN;

CREATE TABLE public.tenants (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name        VARCHAR(150) NOT NULL,
    schema_name VARCHAR(63) NOT NULL UNIQUE,
    status      VARCHAR(40) NOT NULL DEFAULT 'PENDING_SETUP',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT tenants_schema_name_check
        CHECK (schema_name ~ '^tenant_[a-z0-9_]+$')
);

CREATE TABLE public.modules (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR NOT NULL,
    code        VARCHAR(40) NOT NULL UNIQUE,
    description TEXT NOT NULL
);

CREATE TABLE public.tenant_modules (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  UUID NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    module_key VARCHAR(40) NOT NULL REFERENCES public.modules(code),
    enabled_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, module_key)
);

CREATE TABLE public.users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR NOT NULL UNIQUE,
    full_name     VARCHAR NOT NULL,
    password_hash VARCHAR NOT NULL,
    is_active     BOOLEAN NOT NULL DEFAULT true,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.tenant_memberships (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    tenant_id  UUID NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, tenant_id)
);

-- Rôles métier de l'application ; aucun rôle PostgreSQL n'est créé.
CREATE TABLE public.user_roles (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    tenant_id  UUID REFERENCES public.tenants(id) ON DELETE CASCADE,
    role       VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, tenant_id, role),
    CONSTRAINT fk_role_membership
        FOREIGN KEY (user_id, tenant_id)
        REFERENCES public.tenant_memberships(user_id, tenant_id),
    CONSTRAINT user_roles_role_check
        CHECK (role IN ('STUDENT', 'EMPLOYEE', 'STORE_ADMIN', 'TENANT_ADMIN', 'PLATFORM_ADMIN')),
    CONSTRAINT user_roles_tenant_scope_check
        CHECK (
            (role IN ('STUDENT', 'PLATFORM_ADMIN') AND tenant_id IS NULL)
            OR
            (role IN ('EMPLOYEE', 'STORE_ADMIN', 'TENANT_ADMIN') AND tenant_id IS NOT NULL)
        )
);

CREATE UNIQUE INDEX unique_global_role
    ON public.user_roles(user_id, role) WHERE tenant_id IS NULL;

CREATE UNIQUE INDEX unique_tenant_admin_per_user
    ON public.user_roles(user_id) WHERE role = 'TENANT_ADMIN';

CREATE TABLE public.process (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      UUID NOT NULL REFERENCES public.tenants(id),
    name           VARCHAR(150) NOT NULL,
    effective_date TIMESTAMPTZ NOT NULL,
    end_date       TIMESTAMPTZ,
    active         BOOLEAN NOT NULL DEFAULT true,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT process_dates_check
        CHECK (end_date IS NULL OR end_date > effective_date)
);

CREATE INDEX process_tenant_date_idx
    ON public.process(tenant_id, effective_date);

-- Référence publique stable d'un panier situé dans un schéma tenant.
-- basket_id est un lien logique : la cible varie selon tenants.schema_name.
-- Il n'existe donc pas de FK SQL de basket_id vers une table tenant variable.
CREATE TABLE public.published_baskets (
    id        UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id UUID NOT NULL REFERENCES public.tenants(id) ON DELETE RESTRICT,
    basket_id BIGINT NOT NULL,
    UNIQUE (tenant_id, basket_id)
);

CREATE TABLE public.reservations (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    student_id          BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    published_basket_id UUID NOT NULL REFERENCES public.published_baskets(id) ON DELETE RESTRICT,
    status              VARCHAR NOT NULL DEFAULT 'PENDING',
    reserved_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    picked_up_at        TIMESTAMPTZ,
    CONSTRAINT reservations_status_check
        CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'PICKED_UP'))
);

CREATE INDEX reservations_student_id_idx
    ON public.reservations(student_id);

CREATE INDEX reservations_published_basket_id_idx
    ON public.reservations(published_basket_id);

COMMIT;

